// Объем массива - 1249280 байт
//
{
 WORD  bitg,cc,crd,ncomb,sigma,Nzp,Zd;
 DWORD i,j,k,n1,Nzpd;
 BYTE  B;

 n1=0;
 Nzpd=0;
 Zd=0;

 for(k=0;k<610;k++)
 {
  Nzp=0;
  sigma=0;
  ncomb=0;
  crd=7;
  for(i=0;i<2048;i++)
  {
   B=*(Noise+i+(k<<11));
   for(j=0;j<8;j++)
   {
    bitg=(B>>j)&1;
    n1+=bitg;
    if (i|j) Nzp+=(cc^bitg);
    if (i|j|k) Nzpd+=(cc^bitg);
    cc=bitg;
    crd=((crd<<1)|bitg)&0x7;
    if (ncomb==crd)
    {
     if (ncomb==7) sigma++;
     ncomb=(ncomb+1)&0x7;
    }
   }
  }
  if ((Nzp<8065)||(Nzp>8319)) Zd++;
  if ((sigma<245)||(sigma>267)) Zd++;
 }
 if ((n1<4892471L)||(n1>5101769L)) return ERROR;
 if ((Nzpd<4990407L)||(Nzpd>5001831L)) return ERROR;
 if ((Zd<26)||(Zd>82)) return ERROR;

 return OK;
}



