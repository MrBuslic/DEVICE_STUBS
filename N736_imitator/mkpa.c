WORD AutoSync
//
// Автоматический процесс установления
// синхронизации командного канала
//
// ВОЗВРАТ: ERROR1 - ошибка в первом обмене
//          ERROR2 - ошибка во втором обмене
//          ERROR3 - ошибка в третьем обмене
//          OK     - синхронизация установлена
//
(
 BYTE  PR,    // ВХОД:  признак режима (0 - режим ПК1, 1 - режим ПК2)
 BYTE  NKP,   // ВХОД:  номер КП  (1 или 2)
 BYTE  NKL,   // ВХОД:  номер КЛ  (от 1 до 8 включительно)
 DWORD NSYNC, // ВХОД:  номер синхронизации
              //        (слово типа unsigned long, но не более 22 бит)
 WORD  CHECK  // 1 - с контролем квитанций
              // 0 - без контроля квитанций
)
{
 time_t t;
 WORD I;
 WORD ExitCode;
 BYTE Kvit;
 BYTE SCHZK[10];
 BYTE* SCHBK;
 BYTE SYNC[16];
 BYTE OKPI1[4]={0x27,0xAF,0xF9,0x0D};
 BYTE OKPI2[4]={0x11,0xDB,0x92,0x34};
 BYTE ZKPI[16];

 // Формируется СЧЗК
 srand((unsigned) time(&t));
 for (I=0;I<10;I++) SCHZK[I]=rand()&0xff;

 // Формируется синхропосылка
 CreateSync(SCHZK,PR,NKP,NKL,NSYNC,SYNC);

 // И передается по каналу связи в ЛКА
 ExitCode=SendMessageKPI(SYNC,&Kvit,&SCHBK);

 // Если контролируются квитанции
 if (CHECK)
 {
  if (ExitCode^OK) return ERROR1;
  if ((PR==0)&&(Kvit^1)) return ERROR1;
  if ((PR==2)&&(Kvit^2)) return ERROR1;
 }

 // В режиме ПК1 возвращается СЧБК,
 // вызывается функция PrepareSCHBK()
 if (!PR) PrepareSCHBK(SCHBK);

 // Формируется первая проверочная КПИ 1 (искаженная)
 CreateZKPI(OKPI1,1,0,0,1,ZKPI);
 FirstZKPI(ZKPI);
 Sleep(300);
 // И передается по каналу связи в ЛКА
 ExitCode=SendMessageKPI(ZKPI,&Kvit, &SCHBK);

 // Если контролируются квитанции
 if (CHECK)
 {
  if (ExitCode^OK) return ERROR2;
  if (Kvit^11) return ERROR2;
 }

 // Формируется вторая проверочная КПИ1 (не искаженная)
 CreateZKPI(OKPI2,1,0,0,2,ZKPI);

 Sleep(200);
 // И передается по каналу связи в ЛКА
 ExitCode=SendMessageKPI(ZKPI,&Kvit, &SCHBK);

 // Если контролируются квитанции
 if (CHECK)
 {
  if (ExitCode^OK) return ERROR3;
  if (Kvit^3) return ERROR3;
 }

 return OK;
}

void CreateSync
//
// Формирование синхропосылки СП (128 бит) в 16 байтах (тип unsigned char)
// Сформированная синхропосылка должна быть выдана в канал связи в порядке:
//                          0 - младший бит
// SYNC[0]  {   7,  6,...,  0}
// SYNC[1]  {  15, 14,...,  8}
// ...........................
// SYNC[15]  {127,126,...,120}
//            127 - старший бит
//
(
 BYTE  SCHZK[], // ВХОД:   СЧЗК - от ГСЧ
      //        (10 байт типа unsigned char - биты 0..79)
 BYTE  PR,      // ВХОД:  признак режима (0 - режим ПК1, 2 - режим ПК2)
      //        (байт типа unsigned char - биты 80..81)
 BYTE  NKP,     // ВХОД:  номер КП
      //        (байт типа unsigned char - биты 82..85)
 BYTE  NKL,     // ВХОД:  номер КЛ
      //        (байт типа unsigned char - биты 86..89)
 DWORD NSYNC,   // ВХОД:  номер синхронизации
      //        (слово типа unsigned long - биты 90..111)
 BYTE  SYNC[]   // ВЫХОД: синхропосылка СП
      //        (16 байт типа unsigned char - биты 0..127)
)
{
 WORD I;

 for (I=0;I<64;I++) KL_cmd[I]=K_cmd[I+64*(NKL-1)];

 for (I=0;I<10;I++) SYNC[I]=SCHZK[I];
 SYNC[10]=(PR&3)|((NKP&15)<<2)|((NKL&3)<<6);
 SYNC[11]=((NKL>>2)&3)|(BYTE)((NSYNC&0x3f)<<2);
 SYNC[12]=(BYTE)((NSYNC>>6)&0xff);
 SYNC[13]=(BYTE)((NSYNC>>14)&0xff);
 SYNC[14]=SYNC[15]=0;
 for (I=0;I<14;I++)
 {
  SYNC[14]+=SYNC[I];
  SYNC[15]+=SYNC[14];
 }
 for (I=0;I<16;I++) SP_cmd[I]=SYNC[I];
 if (PR) MakeSK();
}

