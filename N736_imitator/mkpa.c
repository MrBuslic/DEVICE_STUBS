WORD StatCtrl(BYTE *Noise)
//
// Статистический контроль ГСЧ
// Шум от ГСЧ передается через указатель
// на массив с шумом от ГСЧ.
// Объем массива - 1250304 байт
//
{
 WORD  bitg,cc,crd,ncomb,sigma,Nzp,Zd;
 DWORD i,j,k,n1,Nzpd;
 BYTE  B;

 n1=0;
 Nzpd=0;
 Zd=0;

 for(k=0;k<4884;k++)
 {
  Nzp=0;
  sigma=0;
  ncomb=0;
  crd=7;
  for(i=0;i<256;i++)
  {
   B=*(Noise+i+k*256);
   for(j=0;j<8;j++)
   {
    bitg=(B>>j)&1;
    n1+=bitg;
    if (i|j|k) Nzp+=(cc^bitg);
    cc=bitg;
    crd=((crd<<1)|bitg)&0x7;
    if (ncomb==crd)
    {
     if (ncomb==7) sigma++;
     ncomb=(ncomb+1)&0x7;
    }
   }
  }
  Nzpd+=Nzp;
  if (k<2442) if ((Nzp<975)||(Nzp>1070)) Zd++;
  if (k>2441) if ((sigma<28)||(sigma>36)) Zd++;
 }

 if ((n1<4896463L)||(n1>5105968L)) return ERROR;
 if ((Nzpd<4994536L)||(Nzpd>5005892L)) return ERROR;
 if ((Zd<125)||(Zd>231)) return ERROR;

 return OK;
}


