void UPU_cmd(void)
{
 WORD I,J,B,N;
 for (I=0;I<520;I++)
 {
  N=RGI_cmd[7]&63;
  B=OZU_cmd[N];
  OZU_cmd[N]=RGI_cmd[0];
  for (J=0;J<7;J++) RGI_cmd[J]=RGI_cmd[J+1];
  RGI_cmd[7]=B;
  if (I==7) for (J=0;J<8;J++) RGI_cmd[J]^=SP_cmd[J+8];
 }
}

void USTUP_cmd(void)
{
 WORD I,J,B;

 for (I=0;I<8;I++)
 for (J=0;J<4;J++)
 {
  RGI_cmd[J]^=RGK_cmd[A_0_cmd];
  RGI_cmd[J+4]=RGI_cmd[J];
  B=RGK_cmd[A_0_cmd]^RGK_cmd[A_2_cmd];
  RGK_cmd[A_0_cmd]=B<<1;
  if (B&0x8000) RGK_cmd[A_0_cmd]^=0x100B;
  A_0_cmd+=1; if (A_0_cmd==31) A_0_cmd=0;
  A_2_cmd+=1; if (A_2_cmd==31) A_2_cmd=0;
 }
}

