/*
Возвращает строку версии ОПО/СПО ЦБК
Вход: нет
Выход: строка ASCIIZ с версией
*/

function ПОЛУЧИТЬ_ВЕРСИЮ_ЦБК_СПО ()
{
var Result = ВЫДАТЬ_ДИР([0x00FF, 0x0002], []);
if (Result) return "";

var Index, Version = "";
for (Index = 0; Index < 32; Index++)
  {
  if (((МКО_БУФЕР[Index] >> 0) & 0xFF) == 0) break;
  Version += String.fromCharCode((МКО_БУФЕР[Index] >> 0) & 0xFF);
  if (((МКО_БУФЕР[Index] >> 8) & 0xFF) == 0) break;
  Version += String.fromCharCode((МКО_БУФЕР[Index] >> 8) & 0xFF);
  }
return Version;
}

