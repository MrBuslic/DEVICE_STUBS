/*
чтение/запись абонентов с повтором при занятости
MkoLine    - линия МКО, 0..1
MkoChan    - канал МКО, 0..1
Addr       - адрес абонента на МКО, 0..31
SubAddr    - подадрес абонента на МКО, 0..31
WordCount  - размер данных для чтения/записи, 1..32
RetryPause - пауза в мсек перед повторным обменом, 0..65535
Data       - данные для записи в абонент
*/

function ЧТЕНИЕ_АБ_ТПО_ПОВТОР (MkoLine, MkoChan, Addr, SubAddr, WordCount, RetryPause)
{
var W2 = (MkoLine & 1) | ((MkoChan & 1) << 1);
var W3 = (Addr & 0x1F) | ((SubAddr & 0x1F) << 5) | ((WordCount & 0x3F) << 10);
return ВЫДАТЬ_ДИР([0xFF, 0x31, W2, W3, RetryPause], []);
}

function ЗАПИСЬ_АБ_ТПО_ПОВТОР (MkoLine, MkoChan, Addr, SubAddr, WordCount, RetryPause, Data)
{
var W2 = (MkoLine & 1) | ((MkoChan & 1) << 1);
var W3 = (Addr & 0x1F) | ((SubAddr & 0x1F) << 5) | ((WordCount & 0x3F) << 10);
return ВЫДАТЬ_ДИР([0xFF, 0x32, W2, W3, RetryPause], Data);
}

/*
управление периодической передачей пакетов по МКО
возможно до 32 одновременно циклически передающихся пакетов
каждый пакет может содержать до 32 сообщений на прием или передачу
интервал цикла передачи пакета от 500 до 60000 мсек
каждый пакет накапливает статистику по удачным/неудачным обменам
*/

// сброс состояния (останов всех передач, очистка всех списков, очистка статистики)
// параметры: нет
function МКО_ЦИКЛ_СБРОС ()
{
return ВЫДАТЬ_ДИР([0x1C62, 0x0000], []);
}

// добавление сообщения в пакет
// параметры: номер пакета (0..31), направление передачи (0=передача, 1=прием), адрес, подадрес, размер данных, данные для передачи
function МКО_ЦИКЛ_ДОБАВИТЬ_СООБЩЕНИЕ (Pack, Dir, Addr, Sub, Size, Data)
{
var W2 = (Pack & 0xFF) | ((Dir & 0xFF) << 8);
var W3 = (Addr & 0xFF) | ((Sub & 0xFF) << 8);
var W4 = (Size & 0xFF);
return ВЫДАТЬ_ДИР([0x1D62, 0x0000, W2, W3, W4], Data);
}

// добавление однократной начальной паузы для пакета
// параметры: номер пакета (0..31), значение паузы, мсек (10..65535)
function МКО_ЦИКЛ_ДОБАВИТЬ_ПАУЗУ (Pack, Pause)
{
var W2 = (Pack & 0xFF);
return ВЫДАТЬ_ДИР([0x1D62, 0x0001, W2, Pause], []);
}

// добавление интервала передачи для пакета
// параметры: номер пакета (0..31), значение интервала, мсек (500..60000)
function МКО_ЦИКЛ_ДОБАВИТЬ_ИНТЕРВАЛ (Pack, Interval)
{
var W2 = (Pack & 0xFF);
return ВЫДАТЬ_ДИР([0x1D62, 0x0002, W2, Interval], []);
}

// добавление линии и канала МКО для пакета
// параметры: номер пакета (0..31), линия МКО, канал МКО
function МКО_ЦИКЛ_ДОБАВИТЬ_КАНАЛ (Pack, Line, Chan)
{
var W2 = (Pack & 0xFF);
var W3 = (Line & 0xFF) | ((Chan & 0xFF) << 8);
return ВЫДАТЬ_ДИР([0x1D62, 0x0003, W2, W3], []);
}

// запуск всех непустых пакетов
// параметры: нет
function МКО_ЦИКЛ_ЗАПУСК_ВСЕХ ()
{
return ВЫДАТЬ_ДИР([0x1E62, 0x0000], []);
}

// останов передачи всех пакетов
// параметры: нет
function МКО_ЦИКЛ_СТОП_ВСЕХ ()
{
return ВЫДАТЬ_ДИР([0x1E62, 0x0002], []);
}

// чтение статистики для пакета
// параметры: номер пакета (0..31)
// выход: [0] - режим пакета (0 - не запущен, 1 - запущен)
// [1][2] - 32-бит общий счетчик передач пакета
// [3][4] - 32-бит счетчик успешных передач пакета
// [5][6] - 32-бит общий неудачных счетчик передач пакета
function МКО_ЦИКЛ_СЧИТАТЬ_СТАТИСТИКУ (Pack)
{
var W2 = (Pack & 0xFF);
return ВЫДАТЬ_ДИР([0x1F62, 0x0000, W2], []);
}

