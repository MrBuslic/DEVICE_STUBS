/*
набор функций модификации ПЗУ ЦБК из ТПО ЦБК, возможные операции:
1 - стереть сектор
2 - проверка сектора на чистоту
3 - сброс буфера сектора
4 - уст линейный адрес для записи
5 - счит линейный адрес
6 - добавить данные в буфер
7 - счит размер данных в буфере
8 - запись со стиранием сектора
9 - запись без стирания сектора

инфо:
распределение ПЗУ ЦБК (8 секторов по 256кб):
сектор 0 (начальный адрес 0x1FC00000) = ОПО ЦБК
сектор 1 (начальный адрес 0x1FC40000) = ОПО ЦБК
сектор 2 (начальный адрес 0x1FC80000) = СПО ЦБК
сектор 3 (начальный адрес 0x1FCC0000) = СПО ЦБК
сектор 4 (начальный адрес 0x1FD00000) = СПО ЦБК
сектор 5 (начальный адрес 0x1FD40000) = СПО ЦБК
сектор 6 (начальный адрес 0x1FD80000) = СПО ЦБК
сектор 7 (начальный адрес 0x1FDC0000) = СПО ЦБК/Таблицы загрузки СПО

инфо:
функции записи позволяют работать только с секторами 2..7
адреса записи и размер данных для записи должны быть выровнены на 4 байта

алгоритм записи данных:
ЦБК_ПЗУ_СТЕРЕТЬ_СЕКТОР(6); // (!!!) если требуется полная очистка сектора, при дозаписи блока пропустить
ЦБК_ПЗУ_ПРОВЕРИТЬ_НА_ЧИСТОТУ(6); // аналогично
ЦБК_ПЗУ_ОЧИСТКА_БУФЕРА_ЗАПИСИ();
ЦБК_ПЗУ_УСТАНОВИТЬ_АДРЕС(0x1FD80000); // возможен другой адрес внутри сектора 6
ЦБК_ПЗУ_ДОБАВИТЬ_ДАННЫЕ([1, 2, 3, 4, 5, 6, 7, 8], 16);
ЦБК_ПЗУ_ТОЛЬКО_ЗАПИСАТЬ(0x10); // 0x10 - только записать, 0x12 - записать и проверить по ТОПСЕГ СПО
// ЦБК_ПЗУ_СТЕРЕТЬ_И_ЗАПИСАТЬ(6, 0x12); // стираем сектор и пишем данные

// (!!!) для считывания записанных данных из ПЗУ исп. функцию 0x06 ТПО
// ВЫДАТЬ_ДИР([0x0006, 16, 0x0000, 0x1FD8], []); // чтение 16 байт с адреса 0x1FD00000
*/

